"""Scaffold a kernel project from a flashinfer-bench definition.

Everything kernel-specific is derived from the definition JSON — the reference
implementation, the stub signature, and the I/O tables in AGENTS.md. Everything
language-specific comes from a profile in assets/lang/. Nothing is hand-transcribed,
because a wrong shape in AGENTS.md misleads the agent for an entire run.
"""

from __future__ import annotations

import json
import shutil
import subprocess
from pathlib import Path

ASSETS = Path(__file__).parent / "assets"

# Language profile -> (flashinfer-bench BuildSpec language, source directory).
# These differ for CuTeDSL: it is Python-JIT so it packs with the triton builder,
# but lives in its own folder so the agent never confuses the two.
BUILD = {
    "triton": ("triton", "triton"),
    "cuda": ("cuda", "cuda"),
    "cutedsl": ("triton", "cutedsl"),
}


def languages() -> list[str]:
    return sorted(p.stem for p in (ASSETS / "lang").glob("*.md"))


def _table(spec: dict, title: str, note: str = "") -> str:
    lines = [f"### {title}{note}", "", "| name | shape | dtype |", "|---|---|---|"]
    for name, s in spec.items():
        shape = s.get("shape")
        shape = "scalar" if not shape else "[" + ", ".join(str(x) for x in shape) + "]"
        lines.append(f"| `{name}` | `{shape}` | {s.get('dtype', '?')} |")
    return "\n".join(lines)


def _kernel_section(defn: dict, source_dir: str, kernel_file: str, baseline_file: str) -> str:
    parts = [
        "## This kernel",
        "",
        f"**Definition:** `{defn['name']}`",
        "",
        defn.get("description", "").strip(),
        "",
        f"**You edit:** `solution/{source_dir}/{kernel_file}` — entry point `kernel`",
        f"**Reference:** `solution/{source_dir}/{baseline_file}` — read for numerical semantics",
        "",
        _table(defn.get("inputs", {}), "Inputs"),
        "",
        _table(
            defn.get("outputs", {}),
            "Outputs",
            " (DPS — pre-allocated and passed in; never allocate these inside the kernel)",
        ),
    ]

    axes = defn.get("axes") or {}
    if axes:
        rows = ["", "### Axes", "", "| axis | kind | detail |", "|---|---|---|"]
        for name, a in axes.items():
            kind = a.get("type", "?")
            detail = (a.get("description") or "").strip()
            if kind == "const":
                fixed = f"always {a.get('value')}"
                detail = f"{fixed} — {detail}" if detail else fixed
            rows.append(f"| `{name}` | {kind} | {detail} |")
        parts.append("\n".join(rows))

    constraints = defn.get("constraints") or []
    if constraints:
        parts.append("\n### Constraints\n\n" + "\n".join(f"- `{c}`" for c in constraints))

    return "\n".join(parts) + "\n"


def _stub(defn: dict) -> str:
    args = list(defn.get("inputs", {})) + list(defn.get("outputs", {}))
    return (
        f'"""Kernel under optimization: {defn["name"]}.\n\n'
        f"{defn.get('description', '').strip()}\n\n"
        "Outputs are destination-passing: write into them, do not allocate.\n"
        '"""\n\n\n'
        f"def kernel({', '.join(args)}):\n"
        '    raise NotImplementedError("implement the fused kernel")\n'
    )


